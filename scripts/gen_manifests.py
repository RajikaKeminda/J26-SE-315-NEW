#!/usr/bin/env python3
"""
gen_manifests.py

Generates the Kubernetes manifests for a topology from autoscaler/src/topologies.py, so
the topology the autoscaler reasons about and the one that is deployed cannot drift apart.

    python scripts/gen_manifests.py                          # demo6 -> k8s/01-services/
    python scripts/gen_manifests.py --topology trainticket14 --out k8s/05-trainticket14

Every service is the SAME image (services/generic-service), configured by environment
variables. Resources use requests == limits (Guaranteed QoS) so a pod's CPU allocation
is one unambiguous number - the quantity the agent resizes. Rollouts use maxSurge=1 /
maxUnavailable=0 so a resize never removes capacity.
"""

import argparse
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, os.path.join(ROOT, "autoscaler"))

from src.topologies import get_topology, validate     # noqa: E402

NAMESPACE = "autoscaler-poc"

TEMPLATE = """\
# GENERATED by scripts/gen_manifests.py from autoscaler/src/topologies.py ({topology}) - edit the topology, not this file.
apiVersion: apps/v1
kind: Deployment
metadata:
  name: {name}
  namespace: {namespace}
  labels:
    app: {name}
spec:
  replicas: {replicas}
  strategy:
    type: RollingUpdate
    rollingUpdate:
      maxSurge: 1
      maxUnavailable: 0
  selector:
    matchLabels:
      app: {name}
  template:
    metadata:
      labels:
        app: {name}
      annotations:
        prometheus.io/scrape: "true"
        prometheus.io/port: "8000"
        prometheus.io/path: "/metrics"
    spec:
      terminationGracePeriodSeconds: 10
      containers:
        - name: {name}
          image: k8s-autoscaler/generic-service:latest
          imagePullPolicy: IfNotPresent
          ports:
            - containerPort: 8000
          env:
            - name: SERVICE_NAME
              value: "{name}"
            - name: DOWNSTREAM
              value: "{downstream}"
            - name: WORK_MS
              value: "{work_ms:g}"
            - name: MAX_CONCURRENCY
              value: "4"
            - name: TRACE_SAMPLE_RATIO
              value: "0.25"
            - name: JAEGER_OTLP_ENDPOINT
              value: "http://jaeger.{namespace}.svc.cluster.local:4318/v1/traces"
          resources:
            requests:
              cpu: "{cpu}"
              memory: "{mem}"
            limits:
              cpu: "{cpu}"
              memory: "{mem}"
          # Probes are deliberately forgiving: an overloaded, CPU-throttled pod must not be
          # killed (liveness) or pulled out of the Service (readiness) just because /health
          # answered slowly - that turns an overload into an outage.
          readinessProbe:
            httpGet:
              path: /health
              port: 8000
            initialDelaySeconds: 1
            periodSeconds: 2
            timeoutSeconds: 3
            failureThreshold: 3
          livenessProbe:
            httpGet:
              path: /health
              port: 8000
            initialDelaySeconds: 10
            periodSeconds: 10
            timeoutSeconds: 5
            failureThreshold: 6
---
apiVersion: v1
kind: Service
metadata:
  name: {name}
  namespace: {namespace}
  labels:
    app: {name}
spec:
  selector:
    app: {name}
  ports:
    - port: 8000
      targetPort: 8000
      name: http
"""


def render(topology, service, cpu="250m", mem="128Mi", replicas=2):
    targets = topology.call_graph.get(service, [])
    downstream = ",".join(f"http://{c}:8000|{w:g}" for c, w in targets)
    return TEMPLATE.format(topology=topology.name, name=service, namespace=NAMESPACE, replicas=replicas,
                           downstream=downstream, work_ms=topology.work(service), cpu=cpu, mem=mem)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--topology", default="demo6")
    ap.add_argument("--out", default=None, help="output directory (default k8s/01-services)")
    ap.add_argument("--cpu", default="250m")
    ap.add_argument("--mem", default="128Mi")
    ap.add_argument("--replicas", type=int, default=2)
    ap.add_argument("--check", action="store_true", help="exit 1 if the files on disk differ")
    args = ap.parse_args()

    topo = get_topology(args.topology)
    validate(topo)
    out = os.path.join(ROOT, args.out or "k8s/01-services")
    os.makedirs(out, exist_ok=True)
    stale = []
    for svc in topo.services:
        text = render(topo, svc, args.cpu, args.mem, args.replicas)
        path = os.path.join(out, f"{svc}.yaml")
        if args.check:
            if not os.path.exists(path) or open(path).read() != text:
                stale.append(path)
        else:
            with open(path, "w") as f:
                f.write(text)
    if args.check:
        if stale:
            print("out of date:", *stale, sep="\n  ")
            sys.exit(1)
        print("manifests match topology", topo.name)
    else:
        print(f"wrote {len(topo.services)} manifests to {out}")


if __name__ == "__main__":
    main()
